ALTER TABLE pokemon_set_catalog
    ADD COLUMN IF NOT EXISTS abbreviation varchar(20);

CREATE TABLE IF NOT EXISTS decks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    name varchar(150) NOT NULL,
    notes varchar(1000),
    created_at timestamp NOT NULL,
    updated_at timestamp NOT NULL,
    CONSTRAINT fk_decks_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX IF NOT EXISTS idx_decks_user_id ON decks (user_id);

CREATE TABLE IF NOT EXISTS deck_cards (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deck_id bigint NOT NULL,
    external_id varchar(50) NOT NULL,
    name varchar(150) NOT NULL,
    card_number varchar(30),
    collection_id varchar(50),
    collection_name varchar(150),
    image_url varchar(1000),
    section varchar(20) NOT NULL,
    quantity integer NOT NULL,
    created_at timestamp NOT NULL,
    updated_at timestamp NOT NULL,
    CONSTRAINT fk_deck_cards_deck
        FOREIGN KEY (deck_id) REFERENCES decks (id) ON DELETE CASCADE,
    CONSTRAINT uk_deck_cards_deck_external_id
        UNIQUE (deck_id, external_id)
);

CREATE INDEX IF NOT EXISTS idx_deck_cards_deck_id ON deck_cards (deck_id);
